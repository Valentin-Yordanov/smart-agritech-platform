function slugify(value: string): string {
  return value.trim().toLowerCase().replace(/[\s-]+/g, '_');
}

export function localizeCrop(name: string, lang: Language): string {
  if (lang === 'en') return name;
  return CROPS_BG[name] ?? name;
}

export function localizePart(part: string, lang: Language): string {
  if (lang === 'en') return part;
  return PARTS_BG[part.toLowerCase()] ?? part;
}

/** Accepts either a class slug (`late_blight`) or the English label (`Late Blight`). */
export function localizeCondition(value: string, lang: Language): string {
  if (lang === 'en') return value;
  return CONDITIONS_BG[slugify(value)] ?? value;
}
